import catalog from './catalog.json';

export type HardwareCategory = string;
export type HardwareFinish = string;

export interface Product {
  id: string;
  slug: string;
  name: string;
  category: string;
  finish: string;
  finishes: string[];
  size?: string;
  image: string;
  tier: 'ready' | 'extra';
  opaque: boolean;
  price?: number; // In PKR, undefined = "Price on request"
  description: string;
  featured?: boolean;
  specs?: {
    material: string;
    projection?: string;
    fixing?: string;
    weight?: string;
  };
}

interface CatalogProduct {
  id: number;
  slug: string;
  name: string;
  category: string;
  finish: string;
  background: 'white' | 'scene';
  images: Array<{
    full: string;
    thumb: string;
  }>;
}

/**
 * Optional user overrides keyed by product slug.
 * Allows customizing name, price, description, featured, or hidden status.
 */
export interface ProductOverride {
  name?: string;
  price?: number;
  description?: string;
  featured?: boolean;
  hidden?: boolean;
  category?: string;
  finish?: string;
  size?: string;
  specs?: {
    material: string;
    projection?: string;
    fixing?: string;
    weight?: string;
  };
}

export const PRODUCT_OVERRIDES: Record<string, ProductOverride> = {};

const formatLabel = (value: string) => value
  .split(/[-_\s]+/)
  .filter(Boolean)
  .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
  .join(' ');

/**
 * The storefront's canonical product array. `catalog.json` is generated by
 * the catalogue-processing pipeline; its nested image sets are reduced to the
 * primary image required by the existing product-card and modal components.
 */
export const products: Product[] = (catalog as CatalogProduct[])
  .filter((item) => item.images.length > 0 && !PRODUCT_OVERRIDES[item.slug]?.hidden)
  .map((item) => {
    const override = PRODUCT_OVERRIDES[item.slug] || {};
    const finish = override.finish || formatLabel(item.finish);
    return {
      id: `catalog-${item.id}`,
      slug: item.slug,
      name: override.name || item.name,
      category: override.category || formatLabel(item.category),
      finish,
      finishes: [finish],
      size: override.size || 'Architectural Specification',
      image: item.images[0].full,
      tier: 'ready' as const,
      // Catalogue imagery now retains the original photography, so never use
      // the cutout-only multiply blend treatment in SafeImage.
      opaque: false,
      price: override.price !== undefined ? override.price : undefined, // Price stays undefined by default
      description: override.description || `Architectural ${formatLabel(item.category).toLowerCase()} in ${finish.toLowerCase()} finish.`,
      featured: override.featured ?? false,
      specs: override.specs || {
        material: 'Solid Brass & Architectural Metal',
        projection: 'Standard Profile',
        fixing: 'Concealed Fixing',
        weight: 'Solid Core',
      },
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// Backward-compatible name for existing components. New code should import
// the canonical lowercase `products` array above.
export const PRODUCTS = products;

// Category descriptions mapping for rich tiles
const CATEGORY_DESCRIPTIONS: Record<string, string> = {
  'Door Handles': 'Sprung lever handles with ergonomic grips and precision roses',
  'Main Door Pulls': 'Substantial entrance door pulls in solid brass and geometric profiles',
  'Cabinet Handles': 'Precision-crafted cabinet bar handles, fluted pulls and linear grips',
  'Decorative Handles': 'Artisanal statement handles featuring sculpted nature and relief motifs',
  Knobs: 'Solid architectural cabinet knobs, textured spheres and geometric turn-pieces',
  'Mortise Locks': 'Heavy-duty architectural locksets and euro-profile security mechanisms',
  Accessories: 'Architectural tower bolts, escutcheon plates and hardware accessories',
  Handles: 'Sprung lever handles with fluted grips and precision roses',
  Pulls: 'Architectural entrance pulls and linear cabinet bars',
};

// Dynamically generate categories with real product counts
const uniqueCategoryNames = Array.from(new Set(PRODUCTS.map((p) => p.category))).sort((a, b) => {
  // Put Door Handles and Main Door Pulls first, then alphabetical
  if (a.toLowerCase().includes('door handle')) return -1;
  if (b.toLowerCase().includes('door handle')) return 1;
  if (a.toLowerCase().includes('pull')) return -1;
  if (b.toLowerCase().includes('pull')) return 1;
  return a.localeCompare(b);
});

export const CATEGORIES_LIST = uniqueCategoryNames.map((catName) => {
  const representative = PRODUCTS.find((p) => p.category === catName);
  return {
    id: catName,
    name: catName,
    description: CATEGORY_DESCRIPTIONS[catName] || 'Architectural hardware pieces',
    count: PRODUCTS.filter((p) => p.category === catName).length,
    image: representative ? representative.image : undefined,
  };
});

// Dynamic finishes list derived directly from product dataset
const uniqueFinishes = Array.from(new Set(PRODUCTS.map((p) => p.finish))).sort();
export const FINISHES_LIST = ['All', ...uniqueFinishes] as const;

export type FinishFilter = typeof FINISHES_LIST[number];
export type CategoryFilter = 'All' | typeof CATEGORIES_LIST[number]['name'];
